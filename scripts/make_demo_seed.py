"""Write sql/05_demo_loans.sql from the golden master.
Loan 9001 is the on-screen demo loan (late payments: late fee, GST, penal, SMA0).
Loan 9002 is the smoke-test loan used by the deploy watcher after every release.
The seed is idempotent: it deletes and recreates both loans, so it doubles as the reset."""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
golden = {c["case_id"]: c for c in json.load(open(ROOT / "golden" / "golden_master.json"))}
PICK = {9001: "C03", 9002: "C01"}

def q(v):
    return "NULL" if v is None else ("'" + str(v).replace("'", "''") + "'")

out = ["-- Demo loans. Generated by scripts/make_demo_seed.py. Safe to re-run: it recreates both loans.",
       "DELETE FROM lms.loan_ledger WHERE loan_id IN (9001, 9002);",
       "DELETE FROM lms.loan_run_summary WHERE loan_id IN (9001, 9002);",
       "DELETE FROM lms.payment WHERE loan_id IN (9001, 9002);",
       "DELETE FROM lms.installment WHERE loan_id IN (9001, 9002);",
       "DELETE FROM lms.loan WHERE loan_id IN (9001, 9002);", ""]
for loan_id, cid in PICK.items():
    inp = golden[cid]["inputs"]; L = inp["loan"]
    out.append(f"-- loan {loan_id}: golden case {cid} ({golden[cid]['scenario']})")
    out.append("INSERT INTO lms.loan (loan_id, customer_ref, product_code, branch_state, disb_date, principal_disbursed, "
               "rate_type, fixed_rate_pct, benchmark_code, spread_pct, reset_months, tenor_months, emi) VALUES ("
               + ", ".join([str(loan_id), q("DEMO-" + str(loan_id)), q(L["product_code"]), q(L["branch_state"]), q(L["disb_date"]),
                            q(L["principal_disbursed"]), q(L["rate_type"]), q(L["fixed_rate_pct"]), q(L["benchmark_code"]),
                            q(L["spread_pct"]), q(L["reset_months"]), q(L["tenor_months"]), q(L["emi"])]) + ");")
    for r in inp["installments"]:
        out.append(f"INSERT INTO lms.installment (loan_id, inst_no, due_date, principal_due) VALUES ({loan_id}, {r['inst_no']}, {q(r['due_date'])}, {r['principal_due']});")
    for i, p in enumerate(inp["payments"], start=1):
        out.append(f"INSERT INTO lms.payment (payment_id, loan_id, pay_date, amount, pay_type) VALUES ({loan_id * 100 + i}, {loan_id}, {q(p['pay_date'])}, {p['amount']}, {q(p['pay_type'])});")
    out.append("")
(ROOT / "sql" / "05_demo_loans.sql").write_text("\n".join(out))
print("wrote sql/05_demo_loans.sql;", {k: len(golden[v]['inputs']['payments']) for k, v in PICK.items()}, "payments")
